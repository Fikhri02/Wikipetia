func TestSchemaHasSlice1Tables(t *testing.T) {
	url := os.Getenv("TEST_DATABASE_URL")
	if url == "" {
		t.Skip("TEST_DATABASE_URL not set")
	}
	conn, err := pgx.Connect(context.Background(), url)
	require.NoError(t, err)
	defer conn.Close(context.Background())

	want := []string{
		"users", "courses", "topics", "modules", "blocks", "block_topics",
		"questions", "enrolments", "block_progress", "topic_mastery", "events",
	}
	for _, table := range want {
		var exists bool
		err := conn.QueryRow(context.Background(),
			`SELECT EXISTS (SELECT 1 FROM information_schema.tables
			 WHERE table_schema='public' AND table_name=$1)`, table).Scan(&exists)
		require.NoError(t, err)
		assert.True(t, exists, "table %s should exist", table)
	}
}

func TestSelfStudyEnrolmentIsUniquePerCourse(t *testing.T) {
	url := os.Getenv("TEST_DATABASE_URL")
	if url == "" {
		t.Skip("TEST_DATABASE_URL not set")
	}
	ctx := context.Background()
	conn, err := pgx.Connect(ctx, url)
	require.NoError(t, err)
	defer conn.Close(ctx)

	tx, err := conn.Begin(ctx)
	require.NoError(t, err)
	defer tx.Rollback(ctx)

	var userID, courseID string
	require.NoError(t, tx.QueryRow(ctx,
		`INSERT INTO users (name) VALUES ('u') RETURNING id`).Scan(&userID))
	require.NoError(t, tx.QueryRow(ctx,
		`INSERT INTO courses (owner_id, title) VALUES ($1,'c') RETURNING id`, userID).Scan(&courseID))

	_, err = tx.Exec(ctx,
		`INSERT INTO enrolments (user_id, course_id, mode) VALUES ($1,$2,'self_study')`, userID, courseID)
	require.NoError(t, err)

	_, err = tx.Exec(ctx,
		`INSERT INTO enrolments (user_id, course_id, mode) VALUES ($1,$2,'self_study')`, userID, courseID)
	require.Error(t, err, "a second self-study enrolment in the same course must be rejected")
}

// TestSortKeyColumnsUseCCollation guards the ordering scheme. Sort keys are
// generated by internal/platform/rank, which compares bytes the way Go does.
// This database's default collation is en_US.utf8, which orders the rank
// alphabet differently ("0aAkV" rather than "0AVak"), so any sort_key column
// missing COLLATE "C" silently scrambles course ordering.
func TestSortKeyColumnsUseCCollation(t *testing.T) {
	url := os.Getenv("TEST_DATABASE_URL")
	if url == "" {
		t.Skip("TEST_DATABASE_URL not set")
	}
	ctx := context.Background()
	conn, err := pgx.Connect(ctx, url)
	require.NoError(t, err)
	defer conn.Close(ctx)

	rows, err := conn.Query(ctx,
		`SELECT table_name, collation_name
		 FROM information_schema.columns
		 WHERE table_schema = 'public' AND column_name = 'sort_key'
		 ORDER BY table_name`)
	require.NoError(t, err)
	defer rows.Close()

	found := 0
	for rows.Next() {
		var table string
		var collation *string
		require.NoError(t, rows.Scan(&table, &collation))
		found++
		require.NotNil(t, collation, "%s.sort_key has no explicit collation", table)
		assert.Equal(t, "C", *collation,
			`%s.sort_key must be COLLATE "C" so ORDER BY matches rank's byte comparison`, table)
	}
	require.NoError(t, rows.Err())
	assert.Equal(t, 4, found, "expected sort_key on topics, modules, blocks and questions")
}
